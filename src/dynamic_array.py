if __name__ == "__main__":
    print("=== ТЕСТИРОВАНИЕ DynamicArray (серебряный уровень) ===")

    # ----- 1. Создание и append -----
    arr = DynamicArray()
    print("1. Пустой массив:", arr)
    for i in range(10):
        arr.append(i * 2)
    print("   После добавления 10 элементов:", arr)
    print("   Длина:", len(arr))
    print("   Ёмкость (внутренняя):", arr._capacity)

    # ----- 2. Доступ по индексу (get) -----
    print("\n2. get(3):", arr.get(3))          # 6
    try:
        print("   get(20):", arr.get(20))
    except IndexError as e:
        print("   Ошибка при get(20):", e)

    # ----- 3. Вставка (insert) -----
    print("\n3. Вставка 999 на позицию 3:")
    arr.insert(3, 999)
    print("   Результат:", arr)

    print("   Вставка -1 в конец (index = len):")
    arr.insert(len(arr), -1)
    print("   Результат:", arr)

    # ----- 4. Удаление (remove) -----
    print("\n4. Удаление элемента с индексом 3 (был 999):")
    arr.remove(3)
    print("   Результат:", arr)

    # ----- 5. Линейный поиск (find) -----
    print("\n5. Линейный поиск:")
    print("   find(6):", arr.find(6))          # индекс 3
    print("   find(100):", arr.find(100))      # None

    # ----- 6. Бинарный поиск (binary_search) -----
    # Сначала отсортируем массив (создадим новый)
    print("\n6. Бинарный поиск (требуется отсортированный массив):")
    sorted_arr = DynamicArray()
    # Берём элементы из arr и сортируем их через встроенную sorted (для простоты)
    sorted_values = sorted(arr._array[i] for i in range(len(arr)))
    for v in sorted_values:
        sorted_arr.append(v)
    print("   Отсортированный массив:", sorted_arr)
    print("   binary_search(6):", sorted_arr.binary_search(6))
    print("   binary_search(100):", sorted_arr.binary_search(100))

    # ----- 7. Проверка автоматического сжатия (shrink) -----
    print("\n7. Проверка сжатия (shrink):")
    # Заполняем много элементов
    big_arr = DynamicArray()
    for i in range(100):
        big_arr.append(i)
    print("   После 100 добавлений, capacity:", big_arr._capacity)  # 128

    # Удаляем 80 элементов с начала
    for _ in range(80):
        big_arr.remove(0)
    print("   После удаления 80 элементов, size:", len(big_arr))      # 20
    print("   capacity после сжатия (должно быть ~64):", big_arr._capacity)

    print("\n=== ВСЕ ТЕСТЫ ПРОЙДЕНЫ УСПЕШНО ===")
