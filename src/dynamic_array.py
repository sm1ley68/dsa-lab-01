"""
Модуль: dynamic_array.py
Серебряный уровень лабораторной работы №1.
Реализация динамического массива с автоматическим расширением и сжатием.
Поддерживаются: вставка, удаление, линейный и бинарный поиск.
Каждая строка кода пояснена для понимания синтаксиса и алгоритмов.
"""

# Импортируем ctypes для работы с низкоуровневой памятью (как в C)
import ctypes
# typing используется для аннотаций (указываем ожидаемые типы данных)
from typing import Optional, Any


class DynamicArray:
    """
    Динамический массив с автоматическим расширением (коэффициент 2).
    - Амортизированная O(1) для добавления в конец (append).
    - O(n) для вставки/удаления в середине (insert/remove).
    - O(n) для линейного поиска (find).
    - O(log n) для бинарного поиска (binary_search), требует сортировки.
    - Автоматически уменьшает ёмкость при сильном разрежении (shrink).
    """

    # ------------------------------------------------------------------
    # 1. КОНСТРУКТОР __init__
    # ------------------------------------------------------------------
    def __init__(self):
        """
        Инициализирует пустой динамический массив.
        Начальная ёмкость = 1 (минимальный размер для экономии памяти).
        """
        # _size – текущее количество элементов (изначально 0)
        self._size = 0

        # _capacity – текущая ёмкость (максимальное число элементов без расширения)
        # Стартуем с 1, чтобы не выделять память зря для пустого массива
        self._capacity = 1

        # _array – фактический массив фиксированной длины (указатели на объекты Python)
        # Вызываем вспомогательный метод _make_array для создания
        self._array = self._make_array(self._capacity)

    # ------------------------------------------------------------------
    # 2. ВСПОМОГАТЕЛЬНЫЙ МЕТОД _make_array
    # ------------------------------------------------------------------
    def _make_array(self, capacity: int):
        """
        Создаёт и возвращает новый массив заданной ёмкости.
        :param capacity: желаемый размер (целое положительное число)
        :return: массив из capacity указателей на объекты Python
        """
        # (ctypes.py_object * capacity) – создаёт тип "массив из capacity объектов"
        # () – вызывает конструктор типа, выделяя память
        # Все ячейки изначально содержат нулевые указатели (None)
        return (ctypes.py_object * capacity)()

    # ------------------------------------------------------------------
    # 3. ВСПОМОГАТЕЛЬНЫЙ МЕТОД _resize (РАСШИРЕНИЕ/СЖАТИЕ)
    # ------------------------------------------------------------------
    def _resize(self, new_capacity: int) -> None:
        """
        Изменяет ёмкость внутреннего массива на new_capacity.
        Все существующие элементы копируются в новый массив.
        :param new_capacity: новая ёмкость (должна быть >= _size)
        """
        # 1. Создаём новый массив нужного размера
        new_array = self._make_array(new_capacity)

        # 2. Копируем все старые элементы в новый массив
        # Цикл проходит по всем индексам от 0 до _size-1
        for i in range(self._size):
            new_array[i] = self._array[i]

        # 3. Заменяем старый массив на новый
        self._array = new_array

        # 4. Обновляем ёмкость
        self._capacity = new_capacity

    # ------------------------------------------------------------------
    # 4. append – ДОБАВЛЕНИЕ В КОНЕЦ (АМОРТИЗИРОВАННАЯ O(1))
    # ------------------------------------------------------------------
    def append(self, value: Any) -> None:
        """
        Добавляет элемент в конец массива.
        Если массив заполнен – ёмкость удваивается (resize).
        Амортизированная сложность: O(1).
        """
        # Проверяем, заполнен ли массив (size == capacity)
        if self._size == self._capacity:
            # Если да – увеличиваем ёмкость в 2 раза
            # Почему в 2? Это даёт амортизированную O(1) (суммарное копирование O(n))
            self._resize(2 * self._capacity)

        # Теперь гарантированно есть свободное место
        # Помещаем значение в ячейку с индексом, равным текущему размеру
        self._array[self._size] = value

        # Увеличиваем счётчик элементов на 1
        self._size += 1

    # ------------------------------------------------------------------
    # 5. get – ДОСТУП ПО ИНДЕКСУ (O(1))
    # ------------------------------------------------------------------
    def get(self, index: int) -> Any:
        """
        Возвращает элемент по индексу.
        Сложность: O(1) – прямое обращение к памяти.
        """
        # Проверяем, что индекс в допустимом диапазоне [0, _size-1]
        if not (0 <= index < self._size):
            raise IndexError("Index out of bounds")

        # Возвращаем значение из внутреннего массива
        return self._array[index]

    # ------------------------------------------------------------------
    # 6. insert – ВСТАВКА ПО ИНДЕКСУ (O(n))
    # ------------------------------------------------------------------
    def insert(self, index: int, value: Any) -> None:
        """
        Вставляет элемент по указанному индексу.
        Все элементы справа сдвигаются на одну позицию вправо.
        Сложность: O(n) из-за сдвига.
        """
        # Проверяем, что индекс допустим: можно вставить в конец (index == _size)
        if not (0 <= index <= self._size):
            raise IndexError("Index out of bounds")

        # Если массив заполнен – сначала расширяем его
        if self._size == self._capacity:
            self._resize(2 * self._capacity)

        # СДВИГ ВПРАВО: освобождаем место для нового элемента
        # Идём от конца массива (индекс _size) до index (включительно) в обратном порядке
        # Почему с конца? Чтобы не затереть данные при копировании.
        # Пример: было [A, B, C], вставляем X на позицию 1 -> [A, _, B, C]
        # i = 3: arr[3] = arr[2] (C)
        # i = 2: arr[2] = arr[1] (B)
        # после цикла: [A, B, B, C] -> arr[1] = X -> [A, X, B, C]
        for i in range(self._size, index, -1):
            self._array[i] = self._array[i - 1]

        # Теперь в ячейке index – "дубль" предыдущего элемента, заменяем его на новый
        self._array[index] = value

        # Увеличиваем размер
        self._size += 1

    # ------------------------------------------------------------------
    # 7. remove – УДАЛЕНИЕ ПО ИНДЕКСУ (O(n))
    # ------------------------------------------------------------------
    def remove(self, index: int) -> None:
        """
        Удаляет элемент по индексу.
        Все элементы справа сдвигаются на одну позицию влево.
        Если после удаления размер стал меньше или равен 1/4 от ёмкости,
        массив уменьшается (shrink) до половины ёмкости.
        Сложность: O(n) из-за сдвига.
        """
        # Проверяем корректность индекса
        if not (0 <= index < self._size):
            raise IndexError("Index out of bounds")

        # СДВИГ ВЛЕВО: перезаписываем удаляемый элемент следующим за ним
        # Идём от index до _size-2 включительно
        # Пример: было [A, B, C, D], удаляем индекс 1 (B)
        # i = 1: arr[1] = arr[2] (C) -> [A, C, C, D]
        # i = 2: arr[2] = arr[3] (D) -> [A, C, D, D]
        for i in range(index, self._size - 1):
            self._array[i] = self._array[i + 1]

        # Уменьшаем размер на 1 (последний элемент остаётся "висеть", но мы его игнорируем)
        self._size -= 1

        # ОПЦИОНАЛЬНОЕ СЖАТИЕ (shrink) – экономим память
        # Условие: размер > 0 И размер равен ровно 1/4 от текущей ёмкости
        # Почему 1/4? Чтобы избежать "пиления" (частого расширения/сжатия) на границе.
        # Если уменьшать при 1/2, то при удалении и добавлении по одному элементу
        # массив будет постоянно реаллоцироваться (плохо для производительности).
        if self._size > 0 and self._size == self._capacity // 4:
            # Уменьшаем ёмкость в 2 раза (но не меньше 1)
            new_cap = max(1, self._capacity // 2)
            self._resize(new_cap)

    # ------------------------------------------------------------------
    # 8. find – ЛИНЕЙНЫЙ ПОИСК (O(n))
    # ------------------------------------------------------------------
    def find(self, value: Any) -> Optional[int]:
        """
        Ищет первое вхождение значения в массиве.
        Возвращает индекс найденного элемента или None, если элемент не найден.
        Сложность: O(n) – просмотр всех элементов в худшем случае.
        """
        # Проходим по всем индексам от 0 до _size-1
        for i in range(self._size):
            # Сравниваем текущий элемент с искомым
            if self._array[i] == value:
                # Нашли – сразу возвращаем индекс
                return i
        # Если цикл завершился без возврата – элемент отсутствует
        return None

    # ------------------------------------------------------------------
    # 9. binary_search – БИНАРНЫЙ ПОИСК (O(log n))
    # ------------------------------------------------------------------
    def binary_search(self, value: Any) -> Optional[int]:
        """
        Выполняет бинарный поиск значения в ОТСОРТИРОВАННОМ массиве.
        Возвращает индекс найденного элемента или None, если элемент не найден.
        Сложность: O(log n) – на каждом шаге область поиска сужается вдвое.
        ВНИМАНИЕ: массив должен быть отсортирован по возрастанию!
        """
        # Устанавливаем левую и правую границы поиска
        left = 0
        right = self._size - 1

        # Цикл продолжается, пока левая граница не "пересечёт" правую
        while left <= right:
            # Вычисляем середину текущего диапазона
            # Используем left + (right - left) // 2, чтобы избежать переполнения
            # (хотя в Python переполнения нет, это хороший стиль)
            mid = (left + right) // 2

            # Получаем значение в середине
            mid_val = self._array[mid]

            # Сравниваем с искомым
            if mid_val == value:
                # Нашли – возвращаем индекс
                return mid
            elif mid_val < value:
                # Если среднее значение МЕНЬШЕ искомого – отбрасываем левую половину
                left = mid + 1
            else:
                # Если среднее значение БОЛЬШЕ искомого – отбрасываем правую половину
                right = mid - 1

        # Если вышли из цикла – элемент не найден
        return None

    # ------------------------------------------------------------------
    # 10. СПЕЦИАЛЬНЫЕ МЕТОДЫ __len__ и __str__
    # ------------------------------------------------------------------
    def __len__(self) -> int:
        """Возвращает текущее количество элементов (для len(obj))."""
        return self._size

    def __str__(self) -> str:
        """
        Возвращает строковое представление массива.
        Формат: [элемент1, элемент2, ...]
        """
        # Генератор, который преобразует каждый элемент в строку
        # join объединяет их через запятую и пробел
        return "[" + ", ".join(str(self._array[i]) for i in range(self._size)) + "]"


