"""
Модуль: static_array.py
Бронзовый уровень лабораторной работы №1.
Реализация статического массива фиксированного размера.
Каждая строка кода пояснена для понимания синтаксиса и логики.
"""

# Импортируем модуль ctypes для работы с низкоуровневыми типами C
# В нём есть тип py_object – указатель на любой объект Python
import ctypes


class StaticArray:
    """
    Класс, представляющий статический массив фиксированной ёмкости.
    Поддерживает:
    - доступ по индексу (get, set)
    - добавление в конец (append)
    - получение длины (len)
    - строковое представление (print)
    """

    # ------------------------------------------------------------------
    # МЕТОД-КОНСТРУКТОР: вызывается при создании объекта StaticArray
    # ------------------------------------------------------------------
    def __init__(self, capacity: int):
        """
        :param capacity: максимальное количество элементов (целое > 0)
        """
        # Проверяем, что ёмкость положительная
        # Если нет – генерируем исключение ValueError с пояснением
        if capacity <= 0:
            raise ValueError("Capacity must be positive")

        # self – ссылка на создаваемый объект
        # _capacity – атрибут, хранящий максимальную ёмкость
        # Одно подчёркивание в начале – соглашение о "приватности"
        self._capacity = capacity

        # _size – текущее количество элементов (изначально 0)
        self._size = 0

        # Создаём настоящий массив фиксированной длины в памяти
        # (ctypes.py_object * capacity) – создаёт тип "массив из capacity объектов Python"
        # После этого пишем () – создаём экземпляр этого типа (выделяем память)
        # Все ячейки изначально содержат нулевые указатели (None)
        self._array = (ctypes.py_object * capacity)()

    # ------------------------------------------------------------------
    # МЕТОД get(index) – доступ к элементу по индексу (чтение)
    # ------------------------------------------------------------------
    def get(self, index: int):
        """
        Возвращает элемент по индексу.
        Сложность: O(1) – вычисление адреса одной операцией.
        """
        # Проверяем, что индекс находится в допустимом диапазоне:
        # от 0 до _size-1 включительно
        # Если нет – выбрасываем IndexError
        if not (0 <= index < self._size):
            raise IndexError("Index out of bounds")

        # Возвращаем значение из внутреннего массива по индексу
        return self._array[index]

    # ------------------------------------------------------------------
    # МЕТОД set(index, value) – запись значения по индексу
    # ------------------------------------------------------------------
    def set(self, index: int, value):
        """
        Устанавливает значение по индексу.
        Сложность: O(1).
        """
        # Аналогичная проверка индекса
        if not (0 <= index < self._size):
            raise IndexError("Index out of bounds")

        # Присваиваем новое значение в ячейку массива
        self._array[index] = value

    # ------------------------------------------------------------------
    # МЕТОД append(value) – добавление элемента в конец
    # ------------------------------------------------------------------
    def append(self, value):
        """
        Добавляет элемент в конец массива, если есть свободное место.
        Если массив уже заполнен – генерируется OverflowError.
        """
        # Проверяем, не достигли ли предела ёмкости
        if self._size >= self._capacity:
            raise OverflowError("Array is full")

        # Помещаем значение в первую свободную ячейку (индекс = текущий размер)
        self._array[self._size] = value

        # Увеличиваем счётчик элементов на 1
        self._size += 1

    # ------------------------------------------------------------------
    # СПЕЦИАЛЬНЫЙ МЕТОД __len__ – вызывается при вызове len(obj)
    # ------------------------------------------------------------------
    def __len__(self):
        """
        Возвращает текущее количество элементов в массиве.
        """
        return self._size

    # ------------------------------------------------------------------
    # СПЕЦИАЛЬНЫЙ МЕТОД __str__ – вызывается при print(obj) или str(obj)
    # ------------------------------------------------------------------
    def __str__(self):
        """
        Возвращает строковое представление массива в формате [элемент1, элемент2, ...]
        """
        # Создаём генератор, который проходит по всем индексам от 0 до _size-1
        # и преобразует каждый элемент в строку
        # join объединяет все строки через запятую и пробел
        # Добавляем квадратные скобки в начале и в конце
        return "[" + ", ".join(str(self._array[i]) for i in range(self._size)) + "]"


# ----------------------------------------------------------------------
# БЛОК ТЕСТИРОВАНИЯ (запускается только при выполнении этого файла)
# ----------------------------------------------------------------------
if __name__ == "__main__":
    print("=== Тестирование StaticArray (бронзовый уровень) ===")

    # 1. Создаём массив на 5 элементов
    arr = StaticArray(5)
    print("Создан пустой массив:", arr)

    # 2. Заполняем его значениями
    for i in range(5):
        arr.append(i * 10)
    print("После добавления 5 элементов:", arr)
    print("Длина:", len(arr))

    # 3. Проверяем доступ по индексу
    print("Элемент с индексом 2:", arr.get(2))
    arr.set(2, 999)
    print("После изменения индекса 2 на 999:", arr)

    # 4. Проверяем обработку ошибок – выход за границы
    try:
        arr.get(10)
    except IndexError as e:
        print("Ошибка при get(10):", e)

    # 5. Проверяем переполнение
    try:
        arr.append(100)
    except OverflowError as e:
        print("Ошибка при добавлении 6-го элемента:", e)

    # 6. Вывод итогового состояния
    print("Итоговый массив:", arr)
    print("Длина:", len(arr))

    print("\n=== Тест пройден. Код работает корректно. ===")
